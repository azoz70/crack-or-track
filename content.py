def localize_stage(stage, lang):
    """Return a stage view with fields translated to `lang` (only if present)."""
    if lang != "ar":
        return stage
    s = dict(stage)
    pairs = [("prompt_ar", "prompt"), ("explain_ar", "explain"), ("title_ar", "title"),
             ("objective_ar", "objective"), ("concept_ar", "concept"),
             ("example_ar", "example"), ("tip_ar", "tip"), ("data_ar", "data"),
             ("options_ar", "options"), ("option_explanations_ar", "option_explanations"),
             ("hint_levels_ar", "hint_levels"), ("remediation_options_ar", "remediation_options")]
    for src, dst in pairs:
        if src in stage:
            s[dst] = stage[src]
    return s


def localize_mission(mission, lang):
    """Return a mission view with fields translated to `lang` (only if present)."""
    if lang != "ar" or "story_ar" not in mission:
        return mission
    m = dict(mission)
    pairs = [("story_ar", "story"), ("title_ar", "title"), ("category_ar", "category"),
             ("objectives_ar", "objectives"), ("explanation_ar", "explanation"),
             ("real_world_ar", "real_world"), ("hints_ar", "hints")]
    for src, dst in pairs:
        if src in mission:
            m[dst] = mission[src]
    m["stages"] = [localize_stage(s, lang) for s in mission["stages"]]
    return m
